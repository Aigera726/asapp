/**
 * Доступен ли демо-режим в этой сборке.
 *
 * В dev — всегда. В собранном приложении — только если сборка сделана с
 * EXPO_PUBLIC_ENABLE_DEMO=1.
 *
 * Зачем флаг, а не просто __DEV__: демонстрационный веб-экспорт для
 * бизнес-аналитиков должен показывать приложение на тестовых данных без
 * логина и без обращения к серверу, а боевой APK — не должен получить кнопку
 * «Демо-режим» вовсе. Демо-данные лежат в той же локальной базе, что и
 * рабочие, и в production такой кнопке не место.
 */
export const DEMO_BUILD =
  __DEV__ || process.env.EXPO_PUBLIC_ENABLE_DEMO === '1';
