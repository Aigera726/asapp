export function uiLabel(source: string, language: Language): string {
  const key = Object.prototype.hasOwnProperty.call(UI_LABEL_KEYS, source) ? UI_LABEL_KEYS[source] : undefined;
  return key ? translate(language, key) : source;
}
/** Pure helpers and async notifications read the currently selected language. */
export function currentText(key: TranslationKey, params?: TranslationParams): string {
  return translate(useLanguageStore.getState().language, key, params);
}
export function currentLanguage(): Language { return useLanguageStore.getState().language; }
